# Generate bench/app-async/app.R from bench/app/app.R: the same app, except
# that the CPU job runs in a shiny::ExtendedTask on mirai daemons, so that
# the session's own event loop stays free while it runs.
#   Rscript bench/app-async/make-app.R
# BENCH_DAEMONS (default 1) sets the number of daemons of each app process.
here <- if (file.exists("bench/app/app.R")) "bench" else "."
s <- paste(readLines(file.path(here, "app/app.R")), collapse = "\n")
replace <- function(old, new) {
  stopifnot(grepl(old, s, fixed = TRUE))
  s <<- sub(old, new, s, fixed = TRUE)
}
replace("library(shiny)\n", paste0(
  "library(shiny)\n",
  "# Each app process starts its own daemons, and stops them with the app\n",
  "mirai::daemons(as.integer(Sys.getenv(\"BENCH_DAEMONS\", \"1\")))\n",
  "onStop(function() mirai::daemons(0))\n"))
replace('  output$cpu_out <- renderText({
    req(input$cpu)
    r <- parse_request(input$cpu)
    answer(r$id, session, burn(r$amount))
  })', '  # The CPU job runs on a daemon; the session answers other inputs meanwhile
  cpu_task <- ExtendedTask$new(function(id, amount) {
    mirai::mirai(list(id = id, value = burn(amount)), burn = burn, amount = amount, id = id)
  })
  observeEvent(input$cpu, {
    r <- parse_request(input$cpu)
    cpu_task$invoke(r$id, r$amount)
  })
  output$cpu_out <- renderText({
    result <- cpu_task$result()
    answer(result$id, session, result$value)
  })')
writeLines(c("# GENERATED by bench/app-async/make-app.R from bench/app/app.R; do not edit.", s),
  file.path(here, "app-async/app.R"))
cat("written\n")
